const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('supabase/functions/swimmer-public-profile/laps.ts','utf8');
const {stripTypeScriptTypes} = require('node:module');
const context={}; vm.createContext(context);
vm.runInContext(stripTypeScriptTypes(source.replace('export function','function')),context);
const merge=(r,m)=>JSON.parse(JSON.stringify(context.mergePublicLaps(r,m)));
const manual=[25,50,75].map(d=>({distance:d,cumulative_seconds:d/2}));
let r={distance:100,time_seconds:50,laps:[]};
assert.deepEqual(merge(r,manual).map(x=>x.split_time),['0:12.50','0:12.50','0:12.50','0:12.50']);
r.laps=[{distance:50,cumulative_time:'0:24.00',split_time:'0:24.00'},{distance:100,cumulative_time:'0:50.00',split_time:'0:26.00'}];
let combined=merge(r,manual);
assert.deepEqual(combined.map(x=>x.cumulative_time),['0:12.50','0:24.00','0:37.50','0:50.00']);
assert.equal(combined[1].lap_source,'official');
assert.equal(combined[1].split_time,'0:11.50');
assert.equal(manual[1].cumulative_seconds,25);
assert.equal(merge(r,[{distance:25,cumulative_seconds:30}])[0].distance,50);
assert.equal(merge({...r,laps:JSON.stringify(r.laps)},manual).length,4);
assert.equal(merge({distance:200,time_seconds:120,laps:[]},[25,50,75,100,125,150,175].map(d=>({distance:d,cumulative_seconds:d*.6}))).length,8);
assert.equal(merge({...r,laps:[]},[]).length,0);
console.log('8 manual/official lap checks passed');
