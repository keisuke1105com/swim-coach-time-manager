const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context={PLAYERS:[{id:'a',name:'テスト　選手'}]};vm.createContext(context);
vm.runInContext(fs.readFileSync('video-analysis.js','utf8'),context);
const raw={id:'sample',athlete:'テスト 選手',stroke:'平泳ぎ',distance:25,practiceDate:'2026-10-22',marks:{0:2.985756083338533,5:4.62873185264482,15:11.989544271645084,20:16.218015366017692,25:20.024703686325815}};
const parse=r=>context.parseVideoBackup({format:'swim-split-backup',version:1,records:[r]})[0];
let r=parse(raw);assert.equal(r.playerId,'a');assert.equal(r.total.toFixed(3),'17.039');assert.equal(r.segments[0].speed.toFixed(2),'3.04');assert.equal(r.segments[1].seconds.toFixed(3),'7.361');
assert.ok(parse({...raw,marks:{0:3,25:2}}).error);
assert.ok(parse({...raw,marks:{5:3,25:5}}).error);
assert.ok(parse({...raw,practiceDate:'2026-02-30'}).error);
assert.ok(parse({...raw,marks:{0:null,25:5}}).error);
assert.ok(parse({...raw,marks:{0:0,25:'5'}}).error);
context.PLAYERS.push({id:'b',name:'テスト選手'});assert.equal(parse(raw).playerId,'');
assert.throws(()=>context.parseVideoBackup({format:'other',version:1,records:[]}));
const html=context.videoDetails(parse({...raw,note:'<script>alert(1)</script>',strokeAnalysis:{mode:'cycle',entries:[{from:15,to:20,count:4}]},tempoAnalysis:{samples:[{label:'計測',start:10,end:13,cycles:3}]}}));
assert.ok(html.includes('&lt;script&gt;'));assert.ok(html.includes('1.25m/サイクル'));assert.ok(html.includes('60.0サイクル/分'));
const page=fs.readFileSync('index.html','utf8');
for(const script of page.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g))new vm.Script(script[1]);
assert.ok(page.includes('id="videoAnalysisPanel"'));assert.ok(page.includes('video-analysis.js?v='));
console.log('Video analysis: calculation, validation, matching, escaping, tempo and page syntax passed');
