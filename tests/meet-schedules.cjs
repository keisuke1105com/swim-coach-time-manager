const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.join(__dirname,'..');
const context={window:{}};vm.createContext(context);
for(const file of ['meet-schedules.js','meet-entry-import-ui.js'])vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),context);
const {MeetSchedules:S,renderMeetEventList:render}=context.window;
const meet={id:'9cfab7f6-d11d-4688-a651-dfee38168f26',meet_date:'2026-10-30'};
const schedule=S.forMeet(meet);assert.equal(schedule.days.length,5);
assert.equal(S.forMeet({...meet,id:'other'}),null);
assert.equal(S.forMeet({...meet,meet_date:'2025-10-30'}),null);
const f={id:'f',name:'<選手>',gender:'女子'},m={id:'m',name:'男子選手',gender:'男子'};
const entry=(id,stroke,distance)=>({meet_id:meet.id,swimmer_id:id,stroke,distance,entry_seconds:60,course:'長水路'});
const events=[entry('m','バタフライ',50),entry('f','自由形',100),entry('m','背泳ぎ',200),entry('f','個人メドレー',200),entry('f','自由形',50),entry('f','平泳ぎ',200)];
const races=events.map(e=>S.findRace(schedule,e,e.swimmer_id==='m'?m:f));
assert.deepEqual(Array.from(races,r=>r.day),[5,1,1,2,3,4]);
assert.deepEqual(Array.from(races,r=>r.number),[152,1,4,45,73,115]);
assert.equal(S.findRace(schedule,entry('f','自由形',800),f).round,'タイム決勝');
assert.equal(S.findRace(schedule,entry('f','自由形',1500),f).day,2);
assert.equal(S.findRace(schedule,entry('f','自由形',25),f),null);
assert.equal(S.findRace(schedule,events[0],{gender:''}),null);
const html=render(meet,events,[f,m]);
for(let day=1;day<=5;day++)assert.ok(html.includes('第'+day+'日｜'));
assert.ok(html.includes('第1日｜10/30（2種目）'));
assert.ok(html.indexOf('No.1 ')<html.indexOf('No.4 '));
assert.ok(html.includes('&lt;選手&gt;'));assert.ok(!html.includes('<選手>'));
assert.ok(html.includes('区分決勝・決勝は進出時のみ'));
assert.ok(render(meet,[entry('x','自由形',25)],[]).includes('日程未照合（1種目）'));
assert.ok(render({...meet,id:'other'},[{...events[0],meet_id:'other'}],[m]).includes('出場種目（1件）'));
assert.ok(render(meet,[],[]).includes('出場種目は未登録'));
console.log('meet schedule checks passed');
